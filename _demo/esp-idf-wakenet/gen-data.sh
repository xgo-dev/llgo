#!/bin/bash
# Generate the checked-out-of-git data files for the wakenet demo:
#
#   csmoke/main/samples/hilexin.h   byte-array form   (esp-sr upstream file, verbatim)
#   idfproj/main/wakenet_pcm.c      int16-sample form (converted from the same bytes)
#
# Both are the "Hi, Lexin" wake-word utterance, 16 kHz 16-bit mono, 3.77 s.
# They are NOT in git (15k lines of array literals); every build of this demo
# needs them, so run this script once after cloning. Upstream source:
# espressif/esp-sr test_apps samples (Espressif MIT license).
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
H="$DIR/csmoke/main/samples/hilexin.h"
PCMC="$DIR/idfproj/main/wakenet_pcm.c"

find_hilexin() {
    # 1. A previous IDF build already pulled esp-sr as a managed component.
    local c
    for c in "$DIR"/idfproj/managed_components/espressif__esp-sr/test_apps/*/main/samples/hilexin.h; do
        [[ -f "$c" ]] && { echo "$c"; return; }
    done
    # 2. A local esp-sr clone (any checkout).
    for c in "$HOME"/esp/esp-sr/test_apps/*/main/samples/hilexin.h; do
        [[ -f "$c" ]] && { echo "$c"; return; }
    done
    # 3. Download from upstream (same content, any recent revision).
    c="$(mktemp)"
    curl -fsSL -o "$c" \
        https://raw.githubusercontent.com/espressif/esp-sr/master/test_apps/esp-sr-vadnet/main/samples/hilexin.h
    echo "$c"
}

SRC="$(find_hilexin)"
echo "source: $SRC"

# Byte-array form: verbatim upstream file (the csmoke C test #includes it).
mkdir -p "$(dirname "$H")"
cp "$SRC" "$H"

# int16 form: reinterpret the little-endian byte pairs as signed samples and
# emit the C array the idfproj glue feeds to the detector.
python3 - "$H" "$PCMC" <<'EOF'
import re, struct, sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
body = text.split('{', 1)[1].split('}', 1)[0]
data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))
samples = struct.unpack('<%dh' % (len(data) // 2), data)
with open(dst, 'w') as f:
    f.write('/* The "Hi, Lexin" utterance as 16 kHz 16-bit mono PCM, one int16 per sample.\n')
    f.write(' *\n * GENERATED by ../gen-data.sh from the esp-sr test app sample (Espressif MIT\n')
    f.write(' * license); do not edit. %d samples = %.2f seconds.\n */\n' % (len(samples), len(samples) / 16000.0))
    f.write('#include "wakenet_pcm.h"\n\nconst int16_t hilexin_pcm[%d] = {\n' % len(samples))
    for i in range(0, len(samples), 12):
        f.write('    ' + ', '.join(str(s) for s in samples[i:i+12]) + ',\n')
    f.write('};\n')
print('wrote %s (%d samples)' % (dst, len(samples)))
EOF
echo "wrote $H"
