package llvmfmv

import (
	"fmt"
	"strings"

	"github.com/xgo-dev/llvm"
)

const x86VectorCall llvm.CallConv = 80 // LLVM CallingConv::X86_VectorCall

const wideOrigin = attributePrefix + "wide-origin"

type wideSignature struct {
	typ   llvm.Type
	width int
}

func (sig wideSignature) suffix() string {
	if sig.width == 512 {
		return symbolPrefix + "reg512"
	}
	return symbolPrefix + "reg256"
}

type WideCalls map[string]wideSignature

func CaptureWideCalls(m llvm.Module, arch string) WideCalls {
	if arch != "amd64" {
		return nil
	}
	var calls WideCalls
	td := llvm.NewTargetData(m.DataLayout())
	defer td.Dispose()
	for f := m.FirstFunction(); !f.IsNil(); f = llvm.NextFunction(f) {
		if !hasAttribute(f, EntryAttribute) && !hasAttribute(f, MidwayWideAttribute) {
			continue
		}
		ft := f.GlobalValueType()
		if ft.IsFunctionVarArg() || f.FunctionCallConv() != llvm.CCallConv {
			continue
		}
		width := 0
		valid := true
		for _, t := range append(ft.ParamTypes(), ft.ReturnType()) {
			switch t.TypeKind() {
			case llvm.VectorTypeKind:
				bits := int(td.TypeSizeInBits(t))
				if bits != 256 && bits != 512 {
					valid = false
				}
				width = max(width, bits)
			case llvm.IntegerTypeKind, llvm.FloatTypeKind, llvm.DoubleTypeKind, llvm.PointerTypeKind, llvm.VoidTypeKind:
			default:
				valid = false
			}
		}
		if width == 0 || !valid {
			continue
		}
		if calls == nil {
			calls = make(WideCalls)
		}
		calls[f.Name()] = wideSignature{ft, width}
		f.AddFunctionAttr(m.Context().CreateStringAttribute(wideOrigin, f.Name()))
	}
	return calls
}

// These are LLVM instruction capabilities. They never fold a source-level
// query for a separately controllable CPU flag.
func registerWidth(f llvm.Value, baseline string) int {
	width := 0
	switch baseline {
	case "v4":
		width = 512
	case "v3":
		width = 256
	}
	for _, v := range strings.Split(stringAttribute(f, "target-features"), ",") {
		switch v {
		case "+avx512f":
			width = 512
		case "+avx2":
			width = max(width, 256)
		case "-avx512f":
			width = min(width, 256)
		case "-avx", "-avx2":
			width = 0
		}
	}
	return width
}

// Check the canonical loads and stores generated by LowerWideVectorCalls.
// An address taken by any other consumer must retain the pointer ABI.
func registerShape(fn llvm.Value, ft llvm.Type) bool {
	offset := 0
	if ft.ReturnType().TypeKind() == llvm.VectorTypeKind {
		offset = 1
	}
	if ft.ParamTypesCount()+offset != fn.ParamsCount() {
		return false
	}
	if offset != 0 {
		sret := fn.GetEnumAttributeAtIndex(1, llvm.AttributeKindID("sret"))
		if sret.IsNil() || sret.GetTypeValue() != ft.ReturnType() {
			return false
		}
		for use := fn.Param(0).FirstUse(); !use.IsNil(); use = use.NextUse() {
			store := use.User()
			if store.IsAStoreInst().IsNil() || !store.IsVolatile() || store.Operand(0).Type() != ft.ReturnType() || llvm.NextInstruction(store).IsNil() || llvm.NextInstruction(store).InstructionOpcode() != llvm.Ret {
				return false
			}
		}
		for bb := fn.FirstBasicBlock(); !bb.IsNil(); bb = llvm.NextBasicBlock(bb) {
			ret := bb.LastInstruction()
			if ret.InstructionOpcode() == llvm.Ret {
				prev := llvm.PrevInstruction(ret)
				if prev.IsNil() || prev.IsAStoreInst().IsNil() || prev.Operand(1) != fn.Param(0) {
					return false
				}
			}
		}
	} else if ft.ReturnType() != fn.GlobalValueType().ReturnType() {
		return false
	}
	for i, t := range ft.ParamTypes() {
		param := fn.Param(i + offset)
		if t.TypeKind() != llvm.VectorTypeKind {
			if param.Type() != t {
				return false
			}
			continue
		}
		if param.Type().TypeKind() != llvm.PointerTypeKind {
			return false
		}
		for use := param.FirstUse(); !use.IsNil(); use = use.NextUse() {
			load := use.User()
			if load.IsALoadInst().IsNil() || !load.IsVolatile() || load.Type() != t {
				return false
			}
		}
	}
	return true
}

func (s WideCalls) Promote(mod llvm.Module, baseline string, providers map[string]RegisterProvider) error {
	if len(s) == 0 {
		return nil
	}
	entries := make(map[llvm.Value]llvm.Value)
	// Reserve the register namespace before changing any call or metadata.
	for target := mod.FirstFunction(); !target.IsNil(); target = llvm.NextFunction(target) {
		if target.IsDeclaration() {
			continue
		}
		if sig, ok := s[stringAttribute(target, wideOrigin)]; ok && !mod.NamedValue(target.Name()+sig.suffix()).IsNil() {
			return fmt.Errorf("SIMD register entry collision: %s", target.Name()+sig.suffix())
		}
	}
	var source *sourceInfo
	// Newly appended entries may themselves call ordinary local kernels.
	for caller := mod.FirstFunction(); !caller.IsNil(); caller = llvm.NextFunction(caller) {
		if caller.IsDeclaration() {
			continue
		}
		width := registerWidth(caller, baseline)
		if width == 0 {
			continue
		}
		for bb := caller.FirstBasicBlock(); !bb.IsNil(); bb = llvm.NextBasicBlock(bb) {
			for call := bb.FirstInstruction(); !call.IsNil(); {
				next := llvm.NextInstruction(call)
				target, sig, ok := s.directTarget(call)
				if ok && width >= sig.width {
					entry, seen := entries[target]
					if !seen && target.IsDeclaration() {
						owner := stringAttribute(target, RegisterOwnerAttribute)
						if owner != "" && providers[owner].provides(exportName(stringAttribute(target, wideOrigin), sig)) {
							entry = importRegisterEntry(mod, target, sig)
						}
					} else if !seen && registerShape(target, sig.typ) {
						name := target.Name() + sig.suffix()

						if source == nil {
							source = newSourceInfo(mod)
						}
						entry = makeRegisterEntry(mod, target, sig, name, source)
					}
					entries[target] = entry
					if !entry.IsNil() {
						replaceRegisterCall(call, entry)
					}
				}
				call = next
			}
		}
	}
	for f := mod.FirstFunction(); !f.IsNil(); f = llvm.NextFunction(f) {
		if hasAttribute(f, wideOrigin) {
			f.RemoveStringAttributeAtIndex(-1, wideOrigin)
		}
	}
	return nil
}

func (s WideCalls) directTarget(call llvm.Value) (llvm.Value, wideSignature, bool) {
	if call.IsACallInst().IsNil() || call.TailCallKind() == llvm.TailCallKindMustTail {
		return llvm.Value{}, wideSignature{}, false
	}
	target := call.CalledValue().IsAFunction()
	if target.IsNil() || target.FunctionCallConv() != llvm.CCallConv ||
		call.InstructionCallConv() != target.FunctionCallConv() || call.CalledFunctionType() != target.GlobalValueType() || call.OperandsCount() != target.ParamsCount()+1 {
		return llvm.Value{}, wideSignature{}, false
	}
	switch target.Linkage() {
	case llvm.ExternalLinkage, llvm.PrivateLinkage, llvm.InternalLinkage:
	default:
		return llvm.Value{}, wideSignature{}, false
	}
	ft, ok := s[stringAttribute(target, wideOrigin)]
	return target, ft, ok
}

func makeRegisterEntry(mod llvm.Module, target llvm.Value, sig wideSignature, name string, source *sourceInfo) llvm.Value {
	ft := sig.typ
	body := target.CloneFunction()
	entry := llvm.AddFunction(mod, name, ft)
	entry.CopyFunctionProperties(body)
	entry.SetLinkage(llvm.InternalLinkage)
	entry.SetComdat(llvm.Comdat{})
	for _, attr := range target.GetFunctionAttributes() {
		entry.AddFunctionAttr(attr)
	}
	entry.RemoveStringAttributeAtIndex(-1, wideOrigin)
	entry.RemoveStringAttributeAtIndex(-1, EntryAttribute)
	setRegisterABI(entry, sig, stringAttribute(target, "target-features"))
	entry.SetSubprogram(body.Subprogram())
	body.SetSubprogram(llvm.Metadata{})
	b := mod.Context().NewBuilder()
	defer b.Dispose()
	offset := 0
	if ft.ReturnType().TypeKind() == llvm.VectorTypeKind {
		offset = 1
		for use := body.Param(0).FirstUse(); !use.IsNil(); use = body.Param(0).FirstUse() {
			store := use.User()
			ret := llvm.NextInstruction(store)
			b.SetInsertPointBefore(ret)
			b.CreateRet(store.Operand(0)).InstructionSetDebugLoc(ret.InstructionDebugLoc())
			ret.EraseFromParentAsInstruction()
			store.EraseFromParentAsInstruction()
		}
	} else {
		for _, attr := range body.GetAttributesAtIndex(0) {
			entry.AddAttributeAtIndex(0, attr)
		}
	}
	for i, param := range entry.Params() {
		old := body.Param(i + offset)
		if param.Type().TypeKind() != llvm.VectorTypeKind {
			for _, attr := range body.GetAttributesAtIndex(i + offset + 1) {
				entry.AddAttributeAtIndex(i+1, attr)
			}
			old.ReplaceAllUsesWith(param)
			continue
		}
		for use := old.FirstUse(); !use.IsNil(); use = old.FirstUse() {
			load := use.User()
			load.ReplaceAllUsesWith(param)
			load.EraseFromParentAsInstruction()
		}
	}
	for bb := body.FirstBasicBlock(); !bb.IsNil(); bb = body.FirstBasicBlock() {
		bb.RemoveFromParent()
		llvm.AppendExistingBasicBlock(entry, bb)
	}
	body.EraseFromParentAsFunction()
	source.clone(target, entry)
	return entry
}

func replaceRegisterCall(call, entry llvm.Value) {
	ft := entry.GlobalValueType()
	b := entry.GlobalParent().Context().NewBuilder()
	defer b.Dispose()
	b.SetInsertPointBefore(call)
	offset := 0
	if ft.ReturnType().TypeKind() == llvm.VectorTypeKind {
		offset = 1
	}
	args := make([]llvm.Value, ft.ParamTypesCount())
	for i, t := range ft.ParamTypes() {
		args[i] = call.Operand(i + offset)
		if t.TypeKind() == llvm.VectorTypeKind {
			args[i] = b.CreateLoad(t, args[i], "")
			args[i].SetAlignment(1)
		}
	}
	result := b.CreateCall(ft, entry, args, "")
	result.SetInstructionCallConv(entry.FunctionCallConv())
	result.InstructionSetDebugLoc(call.InstructionDebugLoc())
	for i := 0; i <= len(args); i++ {
		for _, attr := range entry.GetAttributesAtIndex(i) {
			result.AddCallSiteAttribute(i, attr)
		}
	}
	if offset != 0 {
		b.CreateStore(result, call.Operand(0)).SetAlignment(1)
	} else {
		call.ReplaceAllUsesWith(result)
	}
	call.EraseFromParentAsInstruction()
}
