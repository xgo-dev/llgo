//go:build ignore

// Generate the compiler adapter from the go/types source patch. Only the
// package and imports differ, so both consumers execute the same layout rules.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "check generated files without writing")
	flag.Parse()
	std, err := importer.Default().Import("go/types")
	if err != nil {
		panic(err)
	}
	write := func(name string, data []byte) {
		if *check {
			got, err := os.ReadFile(name)
			if err != nil || !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), data) {
				panic(fmt.Sprintf("%s is stale; run go generate ./internal/typesizes", name))
			}
		} else if err := os.WriteFile(name, data, 0644); err != nil {
			panic(err)
		}
	}
	for _, name := range []string{"llgo_sizes.go", "llgo_layout.go", "llgo_tags.go", "llgo_tag_string.go", "llgo_native.go", "llgo_validate.go", "llgo_conversions.go"} {
		data, err := os.ReadFile("../../runtime/_patch/go/types/" + name)
		if err != nil {
			panic(err)
		}
		data = bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, name, data, 0)
		if err != nil {
			panic(err)
		}
		// Qualify only unresolved standard type API names. A dot import also
		// imports LLGo's additions during self-hosting and shadows this package's
		// own declarations. Position edits preserve comments and string literals.
		var offsets []int
		for _, id := range file.Unresolved {
			if !strings.HasPrefix(id.Name, "LLGo") && std.Scope().Lookup(id.Name) != nil {
				offsets = append(offsets, fset.Position(id.Pos()).Offset)
			}
		}
		sort.Sort(sort.Reverse(sort.IntSlice(offsets)))
		for _, offset := range offsets {
			data = append(append(append([]byte(nil), data[:offset]...), "types."...), data[offset:]...)
		}
		replacement := []byte("package typesizes\n")
		if len(offsets) != 0 {
			replacement = []byte("package typesizes\n\nimport \"go/types\"\n")
		}
		data = bytes.Replace(data, []byte("package types\n"), replacement, 1)
		data = append([]byte("// Code generated by go generate; DO NOT EDIT.\n"), data...)
		data, err = format.Source(data)
		if err != nil {
			panic(err)
		}
		write(name, data)
		if name == "llgo_tag_string.go" {
			data = bytes.Replace(data, []byte("package typesizes"), []byte("package reflect"), 1)
			data = bytes.ReplaceAll(data, []byte("LLGoFieldTag"), []byte("llgoFieldTag"))
			write("../../runtime/internal/lib/reflect/llgo_tag_string.go", data)
		}
	}
}
