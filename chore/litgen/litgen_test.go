func TestProcessPathGeneratesPostABITargetMatrix(t *testing.T) {
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	pkgDir, err := os.MkdirTemp(wd, "postabi-matrix-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(pkgDir) })
	path := filepath.Join(pkgDir, "in.go")
	source := "// LITTEST: POST-ABI darwin/arm64 linux/amd64 linux/arm64\npackage main\n\nfunc value(v float32) uint32 { return uint32(v) }\n"
	if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := processPath(path, commandOptions{functions: []string{"value"}, globals: "none"}); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	generated := string(data)
	for _, want := range []string{
		"// NOTE: Assertions have been autogenerated by chore/litgen",
		"// CHECK-LABEL: define i32 @main.value(",
		"// ARM64-NEXT:",
		"// LINUX-AMD64-NEXT:",
	} {
		if !strings.Contains(generated, want) {
			t.Fatalf("generated POST-ABI matrix is missing %q:\n%s", want, generated)
		}
	}
	for _, unwanted := range []string{"// DARWIN-ARM64-", "// LINUX-ARM64-"} {
		if strings.Contains(generated, unwanted) {
			t.Fatalf("generated POST-ABI matrix kept redundant %q checks:\n%s", unwanted, generated)
		}
	}
	checkOpts := commandOptions{updateOnly: true, check: true, globals: "smart"}
	if err := processPath(path, checkOpts); err != nil {
		t.Fatalf("fresh POST-ABI matrix reported stale: %v", err)
	}
}

