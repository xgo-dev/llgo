func TestProcessTreeKeepsManualPostABIAndUpdatesAutogenerated(t *testing.T) {
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	root, err := os.MkdirTemp(wd, "postabi-tree-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(root) })

	defaultDir := filepath.Join(root, "default")
	manualPostABIDir := filepath.Join(root, "postabi-manual")
	autogeneratedPostABIDir := filepath.Join(root, "postabi-autogenerated")
	if err := os.Mkdir(defaultDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(manualPostABIDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(autogeneratedPostABIDir, 0o755); err != nil {
		t.Fatal(err)
	}
	defaultPath := filepath.Join(defaultDir, "in.go")
	manualPostABIPath := filepath.Join(manualPostABIDir, "in.go")
	autogeneratedPostABIPath := filepath.Join(autogeneratedPostABIDir, "in.go")
	if err := os.WriteFile(defaultPath, []byte("// LITTEST\npackage main\n\nfunc value() int { return 1 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	manualPostABISource := "// LITTEST: POST-ABI\npackage main\n\n// CHECK: ret void\nfunc main() {}\n"
	if err := os.WriteFile(manualPostABIPath, []byte(manualPostABISource), 0o644); err != nil {
		t.Fatal(err)
	}
	autogeneratedPostABISource := "// LITTEST: POST-ABI linux/amd64 linux/arm64\n// NOTE: Assertions have been autogenerated by chore/litgen UTC_ARGS: --function=convert --check-globals=none\npackage main\n\nfunc convert(v float32) uint32 { return uint32(v) }\n"
	if err := os.WriteFile(autogeneratedPostABIPath, []byte(autogeneratedPostABISource), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := processPath(root, commandOptions{functions: []string{"value"}, globals: "none"}); err != nil {
		t.Fatal(err)
	}
	generated, err := os.ReadFile(defaultPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(generated), "// CHECK-LABEL: define i64 @main.value()") {
		t.Fatalf("default-stage sibling was not generated:\n%s", generated)
	}
	manualPostABI, err := os.ReadFile(manualPostABIPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(manualPostABI) != manualPostABISource {
		t.Fatalf("manual post-ABI source changed:\n%s", manualPostABI)
	}
	autogeneratedPostABI, err := os.ReadFile(autogeneratedPostABIPath)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"// CHECK-LABEL: define i32 @main.convert(", "// LINUX-AMD64-NEXT:", "// LINUX-ARM64-NEXT:"} {
		if !strings.Contains(string(autogeneratedPostABI), want) {
			t.Fatalf("autogenerated post-ABI matrix is missing %q:\n%s", want, autogeneratedPostABI)
		}
	}
}

