package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"strings"

	"github.com/goplus/gogen"
	"golang.org/x/tools/go/packages"
)

// goLayoutModels changes only inline storage containing ordinary Go functions.
// Pointer and container headers keep their original types; following their
// elements would change neither the containing object's size nor its offsets.
func goLayoutModels(pkg *packages.Package, checks []metadataCheck) (string, []string, error) {
	closure := types.NewStruct([]*types.Var{
		types.NewField(token.NoPos, nil, "code", types.Typ[types.Uintptr], false),
		types.NewField(token.NoPos, nil, "env", types.Typ[types.UnsafePointer], false),
	}, nil)
	files := make(map[string]*ast.File)
	for _, file := range pkg.Syntax {
		files[pkg.Fset.PositionFor(file.Pos(), false).Filename] = file
	}
	models := make(map[types.Type]types.Type)
	var convert func(types.Type) (types.Type, error)
	convert = func(typ types.Type) (types.Type, error) {
		if model, ok := models[typ]; ok {
			return model, nil
		}
		model := typ
		storage := typ
		if _, alias := typ.(*types.Alias); !alias {
			storage = typ.Underlying()
		}
		switch underlying := storage.(type) {
		case *types.Alias:
			rhs, err := convert(underlying.Rhs())
			if err != nil {
				return nil, err
			}
			if rhs != underlying.Rhs() {
				model = rhs
			}
		case *types.Signature:
			model = closure
		case *types.Array:
			elem, err := convert(underlying.Elem())
			if err != nil {
				return nil, err
			}
			if elem != underlying.Elem() {
				model = types.NewArray(elem, underlying.Len())
			}
		case *types.Struct:
			fields := make([]*types.Var, underlying.NumFields())
			tags := make([]string, len(fields))
			changed := false
			for i := range fields {
				field := underlying.Field(i)
				fieldType, err := convert(field.Type())
				if err != nil {
					return nil, err
				}
				changed = changed || fieldType != field.Type()
				// Explicit field names preserve direct offsets without importing
				// the original embedded type's method set into the storage model.
				fields[i] = types.NewField(field.Pos(), field.Pkg(), field.Name(), fieldType, false)
				tags[i] = underlying.Tag(i)
			}
			if changed {
				model = types.NewStruct(fields, tags)
			}
		}
		if model != typ {
			var object *types.TypeName
			switch typ := typ.(type) {
			case *types.Named:
				object = typ.Obj()
			case *types.Alias:
				object = typ.Obj()
			}
			if object != nil {
				// Native callbacks such as cl/_testrt/unsafe.T are one word.
				// Read their declaration, including imported named types, rather
				// than applying the ordinary Go func rule to every signature.
				position := pkg.Fset.PositionFor(object.Pos(), false)
				if position.Filename == "" {
					return nil, fmt.Errorf("layout model %s: missing type declaration position", object.Name())
				}
				file := files[position.Filename]
				if file == nil {
					var err error
					file, err = parser.ParseFile(token.NewFileSet(), position.Filename, nil, parser.ParseComments)
					if err != nil {
						return nil, fmt.Errorf("layout model %s: %w", object.Name(), err)
					}
					files[position.Filename] = file
				}
				for _, declaration := range file.Decls {
					group, ok := declaration.(*ast.GenDecl)
					if !ok || group.Tok != token.TYPE {
						continue
					}
					for _, spec := range group.Specs {
						spec := spec.(*ast.TypeSpec)
						if spec.Name.Name != object.Name() {
							continue
						}
						for _, comments := range []*ast.CommentGroup{group.Doc, spec.Doc} {
							if comments == nil {
								continue
							}
							for _, comment := range comments.List {
								text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
								if text == "llgo:cdecl" || text == "llgo:stdcall" || strings.HasPrefix(text, "llgo:type C") {
									model = typ
								}
							}
						}
					}
				}
			}
		}
		models[typ] = model
		return model, nil
	}
	generated := gogen.NewPackage(pkg.PkgPath, pkg.Name, &gogen.Config{Types: pkg.Types, Fset: pkg.Fset})
	emitted := false
	names := make([]string, len(checks))
	for i, check := range checks {
		if check.identifier != check.name {
			generated.NewTypeDefs().AliasType(check.identifier, check.typ)
			emitted = true
		}
		model, err := convert(check.typ)
		if err != nil {
			return "", nil, err
		}
		names[i] = check.identifier
		if model == check.typ {
			continue
		}
		name := fmt.Sprintf("layoutlintStorage%d", i)
		if pkg.Types.Scope().Lookup(name) != nil {
			return "", nil, fmt.Errorf("%s: generated layout type %s already exists", pkg.PkgPath, name)
		}
		names[i] = name
		generated.NewTypeDefs().NewType(name).InitType(generated, model)
		emitted = true
	}
	if !emitted {
		return "", names, nil
	}
	var source strings.Builder
	source.WriteString("// Code generated by layoutlint. DO NOT EDIT.\n\n")
	if err := generated.WriteTo(&source); err != nil {
		return "", nil, err
	}
	return source.String(), names, nil
}
