func TestGenHeaderGoWordLayout(t *testing.T) {
	clang, err := exec.LookPath("clang")
	if err != nil {
		t.Skip("clang is required to check generated C and C++ layouts")
	}
	for _, tc := range []struct {
		target                llvmgen.Target
		pointerSize, wordSize int
	}{
		{llvmgen.Target{GOOS: "linux", GOARCH: "386"}, 4, 4},
		{llvmgen.Target{GOOS: "linux", GOARCH: "amd64"}, 8, 8},
		{llvmgen.Target{GOOS: "windows", GOARCH: "amd64"}, 8, 8},
		{llvmgen.Target{GOOS: "wasip1", GOARCH: "wasm", WasmProfile: "w32"}, 4, 8},
		{llvmgen.Target{GOOS: "js", GOARCH: "wasm", WasmProfile: "j32", LLVMTarget: "wasm32-unknown-emscripten"}, 4, 8},
		{llvmgen.Target{GOOS: "js", GOARCH: "wasm", WasmProfile: "j64", LLVMTarget: "wasm64-unknown-emscripten"}, 8, 8},
	} {
		t.Run(tc.target.Spec().Triple, func(t *testing.T) {
			prog := llvmgen.NewProgram(&tc.target)
			defer prog.Dispose()
			dir := t.TempDir()
			path := filepath.Join(dir, "goword.h")
			pkg := prog.NewPackage("probe", "probe")
			for name, kind := range map[string]types.BasicKind{
				"SignedWord": types.Int, "UnsignedWord": types.Uint, "CAddress": types.Uintptr,
			} {
				word := types.NewTuple(types.NewVar(token.NoPos, nil, "x", types.Typ[kind]))
				pkg.NewFunc(name, types.NewSignatureType(nil, nil, nil, word, word, false), llvmgen.CDecl)
				pkg.SetExport(name, name)
			}
			if err := GenHeaderFile(prog, []llvmgen.Package{pkg}, "goword", path, false); err != nil {
				t.Fatal(err)
			}
			signedWord, unsignedWord := "intptr_t", "uintptr_t"
			if tc.target.WasmProfile != "" {
				signedWord, unsignedWord = "int64_t", "uint64_t"
			}
			// Freestanding compilation uses Clang's standard integer definitions
			// without requiring a target SDK, libraries, or an executable runner.
			source := fmt.Sprintf(`#include "goword.h"
#include <stddef.h>
#ifdef __cplusplus
#define ASSERT static_assert
#define ALIGNOF alignof
#else
#define ASSERT _Static_assert
#define ALIGNOF _Alignof
#endif
ASSERT(sizeof(void *) == %[1]d, "physical pointer width");
ASSERT(sizeof(((GoString *)0)->n) == %[2]d, "Go string length width");
ASSERT(offsetof(GoString, p) == 0, "Go string data offset");
ASSERT(offsetof(GoString, n) == %[2]d, "Go string length offset");
ASSERT(sizeof(GoString) == 2 * %[2]d, "Go string size");
ASSERT(ALIGNOF(GoString) == %[2]d, "Go string alignment");
ASSERT(sizeof(((GoSlice *)0)->data) == %[1]d, "C slice pointer width");
ASSERT(sizeof(((GoSlice *)0)->len) == %[2]d, "Go slice length width");
ASSERT(sizeof(((GoSlice *)0)->cap) == %[2]d, "Go slice capacity width");
ASSERT(offsetof(GoSlice, data) == 0, "Go slice data offset");
ASSERT(offsetof(GoSlice, len) == %[2]d, "Go slice length offset");
ASSERT(offsetof(GoSlice, cap) == 2 * %[2]d, "Go slice capacity offset");
ASSERT(sizeof(GoSlice) == 3 * %[2]d, "Go slice size");
ASSERT(ALIGNOF(GoSlice) == %[2]d, "Go slice alignment");
#ifdef __cplusplus
extern "C" {
#endif
%[3]s SignedWord(%[3]s);
%[4]s UnsignedWord(%[4]s);
uintptr_t CAddress(uintptr_t);
#ifdef __cplusplus
}
#endif
`, tc.pointerSize, tc.wordSize, signedWord, unsignedWord)
			for _, language := range []struct{ name, standard string }{{"c", "c11"}, {"c++", "c++17"}} {
				t.Run(language.standard, func(t *testing.T) {
					cmd := exec.Command(clang, "--target="+tc.target.Spec().Triple, "-ffreestanding", "-fsyntax-only",
						"-Werror", "-x", language.name, "-std="+language.standard, "-I", dir, "-")
					cmd.Stdin = strings.NewReader(source)
					if output, err := cmd.CombinedOutput(); err != nil {
						t.Fatalf("generated Go ABI declarations: %v\n%s", err, output)
					}
				})
			}
		})
	}
}

func TestCheaderWriterTypes(t *testing.T) {
	prog := llvmgen.NewProgram(nil)
	hw := newCHeaderWriter(prog)

	// Test complex integration scenarios only - basic types are covered by TestGoCTypeName
	tests := []struct {
		name     string
		goType   types.Type
		expected string
	}{
		{
			name: "named struct",
			goType: func() types.Type {
				pkg := types.NewPackage("main", "main")
				s := types.NewStruct([]*types.Var{types.NewField(0, nil, "f1", types.Typ[types.Int], false)}, nil)
				return types.NewNamed(types.NewTypeName(0, pkg, "MyStruct", nil), s, nil)
			}(),
			expected: "typedef struct {\n    intptr_t f1;\n} main_MyStruct;\n\n",
		},
		{
			name: "struct with array field",
			goType: func() types.Type {
				arrayType := types.NewArray(types.Typ[types.Float64], 10)
				return types.NewStruct([]*types.Var{
					types.NewField(0, nil, "Values", arrayType, false),
				}, nil)
			}(),
			expected: "typedef struct {\n    double Values[10];\n} struct_double_Values;\n\n",
		},
		{
			name: "struct with multidimensional array",
			goType: func() types.Type {
				// Create a 2D array: [4][3]int32
				innerArrayType := types.NewArray(types.Typ[types.Int32], 3)
				outerArrayType := types.NewArray(innerArrayType, 4)
				return types.NewStruct([]*types.Var{
					types.NewField(0, nil, "Matrix", outerArrayType, false),
				}, nil)
			}(),
			expected: "typedef struct {\n    int32_t Matrix[4][3];\n} struct_int32_t_Matrix;\n\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			hw.typeBuf.Reset()
			hw.declaredTypes = make(map[string]bool) // Reset declared types for each run

			// Mark predefined Go types as declared (same as in genHeader)
			hw.declaredTypes["GoString"] = true
			hw.declaredTypes["GoSlice"] = true
			hw.declaredTypes["GoMap"] = true
			hw.declaredTypes["GoChan"] = true
			hw.declaredTypes["GoInterface"] = true
			hw.declaredTypes["GoComplex64"] = true
			hw.declaredTypes["GoComplex128"] = true

			if err := hw.writeTypedef(tt.goType); err != nil {
				t.Fatalf("writeTypedef() error = %v", err)
			}
			got := hw.typeBuf.String()
			if got != tt.expected {
				t.Errorf("writeTypedef() got = %q, want %q", got, tt.expected)
			}
		})
	}
}

